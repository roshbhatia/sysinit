          patterns = { "amp" },
          executable_patterns = { "/amp$" },
          argv_patterns = { "^amp%s*$" },
          title_patterns = { "amp" },
        },
        copilot = {
          patterns = { "copilot" },
          executable_patterns = { "/copilot$", "copilot%-language%-server" },
          argv_patterns = { "^copilot%s*$" },
          title_patterns = { "copilot" },
        },
        cursor = {
          patterns = { "cursor%-agent", "cursor" },
          executable_patterns = { "/cursor%-agent$" },
          argv_patterns = { "cursor%-agent" },
          title_patterns = { "cursor" },
        },
        crush = {
          patterns = { "crush" },
          executable_patterns = { "/crush$" },
          argv_patterns = { "^crush%s*$" },
          title_patterns = { "crush" },
        },
        aider = {
          patterns = { "aider" },
          executable_patterns = { "/aider$" },
          argv_patterns = { "^aider%s*$" },
          title_patterns = { "aider" },
        },
        opencode = {
          patterns = { "opencode" },
          executable_patterns = { "opencode%-darwin", "opencode%-linux", "/opencode$" },
          argv_patterns = { "bunx%s+opencode", "npx%s+opencode", "/opencode$" },
          title_patterns = { "opencode" },
        },
      },
    })

    -- Prune stale agent-deck state for closed panes (fixes count-never-decrements bug).
    -- agent-deck's own update-status handler only visits panes that currently exist;
    -- when a pane is closed its entry stays in state.agent_states forever and the count
    -- never decrements. get_all_agent_states() returns the live table by reference so
    -- we can mutate it. This handler runs after agent-deck's (registered first above).
    wezterm.on("update-status", function(window, _pane)
      local all_states = agent_deck.get_all_agent_states()
      local active_ids = {}
      for _, tab in ipairs(window:mux_window():tabs()) do
        for _, p in ipairs(tab:panes()) do
          active_ids[p:pane_id()] = true
        end
      end
      for pane_id in pairs(all_states) do
        if not active_ids[pane_id] then
          all_states[pane_id] = nil
        end
      end
    end)
  end

  -- Per-status icon + urgency rank, shared by the statusline and the session
  -- switcher. Worst-wins ordering: waiting (you must act) > done (your move) >
  -- working > idle. `done` is not an agent-deck status, so we carry our own
  -- icon table rather than relying on agent_deck.get_status_icon for it.
  local agent_state_icons = {
    waiting = "◔",
    done = "✔",
    working = "●",
    idle = "○",
  }
  local agent_state_rank = {
    waiting = 4,
    done = 3,
    working = 2,
    idle = 1,
  }

  local function format_age(secs)
    if not secs or secs < 0 then
      return ""
    end
    if secs < 60 then
      return string.format("%ds", secs)
    elseif secs < 3600 then
      return string.format("%dm", math.floor(secs / 60))
    end
    return string.format("%dh", math.floor(secs / 3600))
  end

  -- Best-effort repo name for a pane: the basename of its current working dir.
  -- Uses only the in-memory mux cwd (no shell-out), tolerates both the Url-object
  -- and the raw `file://host/path` string forms wezterm has returned across
  -- versions, and yields "" on any failure. Branch and dirty are NOT derivable
  -- in-memory — the per-pane state-file bus carries those for out-of-WezTerm
  -- consumers; the render-path rollup deliberately stays shell-out-free.
  local function pane_repo(p)
    local ok, repo = pcall(function()
      local cwd = p:get_current_working_dir()
      if not cwd then
        return ""
      end
      local path
      if type(cwd) == "string" then
        path = (cwd:gsub("^file://[^/]*", ""))
      else
        path = cwd.file_path
      end
      if not path or path == "" then
        return ""
      end
      path = (path:gsub("/+$", ""))
      return path:match("([^/]+)$") or ""
    end)
    if not ok then
      return ""
    end
    return repo or ""
  end

  -- Roll per-pane agent state up to one state per seshy session (= workspace),
  -- AND return the per-pane records visited on the same single walk. For each
  -- live pane: prefer the `agent_state` user-var emitted by the agent lifecycle
  -- hooks (status|reason|since|agent); fall back to agent-deck's scraped status
  -- for panes that set none (hookless agents). Reduce a session's panes
  -- worst-wins, carrying the reason + transition time of the winning pane (oldest
  -- `since` breaks ties so age reflects the longest wait).
  -- Pure in-memory walk of live panes — safe to call on every update-status
  -- tick. Returns two values:
  --   sessions = { [workspace] = { status, reason, since, rank } }
  --   panes    = array of { pane_id, window_id, tab_id, workspace, repo, branch,
  --                          agent, status, reason, since, rank } for every pane
  --              currently holding agent state (branch always "" on this path).
  local function agent_session_states()
    local sessions = {}
    local panes = {}
    local deck_states = agent_deck_ok and agent_deck.get_all_agent_states() or {}

    local ok = pcall(function()
      for _, win in ipairs(wezterm.mux.all_windows()) do
        local workspace = win:get_workspace()
        local window_id = win:window_id()
        for _, tab in ipairs(win:tabs()) do
          local tab_id = tab:tab_id()
          for _, p in ipairs(tab:panes()) do
            local status, reason, since, agent
            local uv = p:get_user_vars()
            local raw = uv and uv.agent_state
            if raw and raw ~= "" then
              local s, r, ts, a = raw:match("^([^|]*)|([^|]*)|([^|]*)|(.*)$")
              if s and agent_state_rank[s] then
                status, reason, since, agent = s, r, tonumber(ts), a
              end
            end
            if not status then
              local deck = deck_states[p:pane_id()]
              if deck and agent_state_rank[deck.status] then
                status = deck.status -- working | waiting | idle; no reason/age
                agent = deck.agent
              end
            end
            if status then
              local rank = agent_state_rank[status]
              -- Per-pane record — same walk, in-memory only. Enough to activate
              -- the exact pane later (window/tab/pane id + workspace).
              panes[#panes + 1] = {
                pane_id = p:pane_id(),
                window_id = window_id,
                tab_id = tab_id,
                workspace = workspace,
                repo = pane_repo(p),
                branch = "", -- not in-memory; the state-file bus carries it
                agent = agent or "",
                status = status,
                reason = reason or "",
                since = since,
                rank = rank,
              }
              -- Session rollup. Higher rank wins; on a tie the older `since`
              -- (smaller number) wins so age reflects the longest-running pane.
              -- A pane with a real `since` beats one without (nil sorts last).
              local cur = sessions[workspace]
              local replace = false
              if not cur or rank > cur.rank then
                replace = true
              elseif rank == cur.rank then
                local a, b = since, cur.since
                if a and (not b or a < b) then
                  replace = true
                end
              end
              if replace then
                sessions[workspace] = {
                  status = status,
                  reason = reason or "",
                  since = since,
                  rank = rank,
                }
              end
            end
          end
        end
      end
    end)
    if not ok then
      return {}, {}
    end
    return sessions, panes
  end

  -- Pick the single most action-needing PANE across every workspace: highest
  -- rank, then oldest `since` (longest wait). Idle panes are held to be
  -- non-actionable, so only `working`/`done`/`waiting` panes are candidates.
  -- Returns the per-pane record (pane_id + window_id + tab_id + workspace — all a
  -- caller needs to activate the exact pane) or nil when nothing is actionable.
  local function worst_agent_pane()
    local _, panes = agent_session_states()
    local now = os.time()
    local best
    for _, rec in ipairs(panes) do
      if rec.rank >= agent_state_rank.working then
        if
          not best
          or rec.rank > best.rank
          or (rec.rank == best.rank and (rec.since or now) < (best.since or now))
        then
          best = rec
        end
      end
    end
    return best
  end

  -- Activate the exact pane a rollup record points at. Pane/tab ids are global,
  -- so the mux calls front the right tab + pane even in a background workspace;
  -- SwitchToWorkspace then brings that window forward when it differs from the
  -- current one. Best-effort — a since-closed pane resolves to nil and no-ops.
  local function activate_agent_pane(win, gui_pane, rec)
    if not rec then
      return
    end
    pcall(function()
      local mp = wezterm.mux.get_pane(rec.pane_id)
      if mp then
        local tab = mp:tab()
        if tab then
          tab:activate()
        end
        mp:activate()
      end
    end)
    if rec.workspace and rec.workspace ~= "" and rec.workspace ~= win:active_workspace() then
      win:perform_action(wezterm.action.SwitchToWorkspace({ name = rec.workspace }), gui_pane)
    end
  end

  -- Statusline component: name the single worst blocked session and its age,
  -- then append how many sessions hold actionable state in total so the user
  -- sees both which is worst and how many others are demanding attention. A
  -- single mux walk (the shared rollup) feeds both the worst pick and the count.
  --
  -- "Actionable" is rank >= working (waiting/done/working); idle is excluded.
  -- When nothing is actionable the component renders nothing (no worst, no `0`
  -- count) — idle-only state is not worth statusline space. When exactly one
  -- session is actionable the count suffix is omitted as redundant.
  local function agent_status()
    local sessions = agent_session_states()
    local now = os.time()
    local best_name, best, count = nil, nil, 0
    for name, st in pairs(sessions) do
      if st.rank >= agent_state_rank.working then
        count = count + 1
        if
          not best
          or st.rank > best.rank
          or (st.rank == best.rank and (st.since or now) < (best.since or now))
        then
          best_name, best = name, st
        end
      end
    end
    if not best then
      return ""
    end
    local icon = agent_state_icons[best.status] or "●"
    local age_str = format_age(best.since and (now - best.since) or nil)
    local text = " " .. icon .. " " .. best_name
    if age_str ~= "" then
      text = text .. " " .. age_str
    end
    -- Total actionable-session count; omitted when this is the only one.
    if count > 1 then
      text = text .. " (" .. count .. ")"
    end
    return wezterm.format({ { Text = text .. " " } })
  end

  -- Per-tab attention indicator. tabline calls this for every tab with the
  -- format-tab-title `TabInformation`; its `active_pane.user_vars` carry the same
  -- `agent_state` the rollup reads. Returns a state icon (+ agent label) prefix,
  -- or "" so the retained default index/cwd/process components render the plain
  -- title when a tab holds no agent (or a malformed user-var). Since it emits a
  -- bare string, the icon inherits the tab's fg color — the glyph alone conveys
  -- the state (◔ waiting / ✔ done / ● working / ○ idle).
  local function tab_agent_indicator(tab)
    local ok, out = pcall(function()
      local p = tab and tab.active_pane
      local uv = p and p.user_vars
      local raw = uv and uv.agent_state
      if not raw or raw == "" then
        return ""
      end
      local s, _r, _ts, a = raw:match("^([^|]*)|([^|]*)|([^|]*)|(.*)$")
      if not s or not agent_state_icons[s] then
        return ""
      end
      if a and a ~= "" then
        return agent_state_icons[s] .. " " .. a .. " "
      end
      return agent_state_icons[s] .. " "
    end)
    if not ok then
      return ""
    end
    return out or ""
  end

  local tabline_ok, tabline = plugin_loader.load("tabline")
  if not tabline_ok then
    wezterm.log_warn("Failed to load tabline.wez: " .. tostring(tabline))
  end
  if tabline_ok then
    tabline.setup({
      options = {
        theme = config.colors,
        -- Enabled so each tab title can carry its own agent-state icon (native
        -- click-to-switch is the only clickable per-tab affordance WezTerm has).
        tabs_enabled = true,
        section_separators = {
          left = "",
          right = "",
        },
        component_separators = {
          left = "",
          right = "",
        },
        tab_separators = {
          left = " |",
          right = "| ",
        },
      },
      sections = {
        tabline_a = {
          "mode",
          locked_indicator,
        },
        tabline_b = {},
        tabline_x = {},
        tabline_y = { agent_status },
        tabline_z = {
          "workspace",
          "domain",
        },
        -- Prepend the agent indicator to tabline's default tab layout so the
        -- state icon leads, and the stock index/cwd/process still show the tab's
        -- short repo/cwd. Defaults mirrored from tabline's config.lua.
        tab_active = {
          tab_agent_indicator,
          "index",
          { "parent", padding = 0 },
          "/",
          { "cwd", padding = { left = 0, right = 1 } },
          { "zoomed", padding = 0 },
        },
        tab_inactive = {
          tab_agent_indicator,
          "index",
          { "process", padding = { left = 0, right = 1 } },
        },
      },
      extensions = {},
    })
    tabline.apply_to_config(config)
  end

  -- Fallback: if tabline plugin didn't load, use native right_status for locked indicator
  if not tabline_ok then
    wezterm.on("update-right-status", function(window, _pane)
      local mode_text = locked_indicator()
      window:set_right_status(wezterm.format({
        { Text = mode_text },
      }))
    end)
  end

  -- Post-process window padding for macOS
  if utils.is_darwin() then
    -- Set window padding AFTER tabline.apply_to_config, which zeroes all padding
    config.window_padding = {
      left = "1cell",
      right = "1cell",
      top = "1cell",
      bottom = "0cell",
    }
  end

  -- sravioli UI toolkit: warp (stdlib) must load first so ribbon/sigil's
  -- deps.lua `require("warp.api")` resolves off package.path. These bypass
  -- wezterm.plugin.require entirely (see plugin_loader).
  plugin_loader.load("warp")
  local ribbon_ok, ribbon = plugin_loader.load("ribbon")
  if not ribbon_ok then
    wezterm.log_warn("Failed to load ribbon.wz: " .. tostring(ribbon))
  end
  local sigil_ok, sigil = plugin_loader.load("sigil")
  if not sigil_ok then
    wezterm.log_warn("Failed to load sigil.wz: " .. tostring(sigil))
  end
  if sigil_ok then
    sigil.setup({
      -- Claude Code's foreground process basename is `.claude-wrapped` (a Bun
      -- Mach-O binary); register it (and aliases) so tabs show a clean glyph
      -- instead of the raw wrapper name.
      overrides = {
        claude = {
          name = "Claude",
          -- Claude's brand sparkle (U+2733), in the brand orange. Marks every
          -- Claude Code tab consistently instead of the raw OSC spinner glyph.
          icon = "✳",
          color = "#D97757",
          aliases = { ".claude-wrapped", "claude-code", "claude-wrapped" },
        },
      },
    })
  end

  -- lantern: runtime appearance picker (colorschemes, fonts, GPU, opacity, …).
  -- Its bundled "flames" (the choice sets) live at <plugin_dir>/plugin/lantern/
  -- flames; lantern.meta locates that dir from either a plugin url containing
  -- "lantern.wz" OR wezterm.GLOBAL.__lantern_plugin_dir. Our Nix-store paths
  -- (/nix/store/HASH-source) carry neither, so we seed the global explicitly
  -- BEFORE loading — otherwise register_builtins() (run at api.lua load) wires
  -- the colorscheme/font/gpu wicks with no choices. Its deps.lua (log/memo/
  -- ribbon/warp) is patched to resolve through plugin_loader instead of
  -- wezterm.plugin.require (see patches/lantern-deps-loader.patch).
  wezterm.GLOBAL = wezterm.GLOBAL or {}
  wezterm.GLOBAL.__lantern_plugin_dir = config_data.plugins and config_data.plugins.lantern
  local lantern_ok, lantern = plugin_loader.load("lantern")
  if not lantern_ok then
    wezterm.log_warn("Failed to load lantern.wz: " .. tostring(lantern))
  end
  if lantern_ok then
    lantern.setup({
      log = { enabled = false },
      -- Baseline the picker's "reset" font size to ours so it round-trips.
      default_font = { font_size = config.font_size },
      color = { opacity = config_data.transparency.opacity },
    })
    -- Restore the appearance the user picked in a previous session.
    lantern.rekindle(config)

    -- One entry point (SUPER+SHIFT+l) instead of the upstream CTRL+SHIFT+c/f/…
    -- bindings, which collide with our copy (CTRL+SHIFT+c) and pane-select
    -- (CTRL+SHIFT+f). Picking a category opens that wick's own selector —
    -- lantern.light.<x>() returns a ready WezTerm action.
    local lantern_categories = {
      { id = "colorscheme", label = "Colorscheme", fn = lantern.light.colorscheme },
      { id = "font", label = "Font", fn = lantern.light.font },
      { id = "font_size", label = "Font size", fn = lantern.light.font_size },
      { id = "font_leading", label = "Font leading", fn = lantern.light.font_leading },
      { id = "font_ligatures", label = "Font ligatures", fn = lantern.light.font_ligatures },
      { id = "gpu", label = "GPU / front end", fn = lantern.light.gpu },
      { id = "window_opacity", label = "Window opacity", fn = lantern.light.window_opacity },
      { id = "window_padding", label = "Window padding", fn = lantern.light.window_padding },
      { id = "inactive_pane_opacity", label = "Inactive pane opacity", fn = lantern.light.inactive_pane_opacity },
      { id = "cursor_style", label = "Cursor style", fn = lantern.light.cursor_style },
      { id = "tab_bar_style", label = "Tab bar style", fn = lantern.light.tab_bar_style },
    }

    config.keys = config.keys or {}
    table.insert(config.keys, {
      key = "l",
      mods = "SUPER|SHIFT",
      action = wezterm.action_callback(function(win, pane)
        if keybindings.locked_mode then
          win:perform_action({ SendKey = { key = "l", mods = "SUPER|SHIFT" } }, pane)
          return
        end
        local choices = {}
        for _, cat in ipairs(lantern_categories) do
          choices[#choices + 1] = { id = cat.id, label = cat.label }
        end
        win:perform_action(
          wezterm.action.InputSelector({
            title = "Appearance",
            fuzzy = true,
            choices = choices,
            action = wezterm.action_callback(function(inner_win, inner_pane, id, _label)
              if not id then
                return
              end
              for _, cat in ipairs(lantern_categories) do
                if cat.id == id then
                  inner_win:perform_action(cat.fn(), inner_pane)
                  return
                end
              end
            end),
          }),
          pane
        )
      end),
    })
  end

  -- Smart tab titles: a sigil process icon + a meaningful label, never empty
  -- and never the bare word "zsh". Label precedence is OSC-2 title (oh-my-posh
  -- emits the folder for shells; TUIs like Claude emit their own summary) ->
  -- cwd basename -> process name. No app-specific slugging: programs that set
  -- an OSC title own their label verbatim.
  local SHELLS = { zsh = true, bash = true, fish = true, sh = true, ["-zsh"] = true }

  wezterm.on("format-tab-title", function(tab, _tabs, _panes, _config, _hover, _max_width)
    -- format-tab-title hands us TabInformation/PaneInformation structs (fields),
    -- NOT MuxTab/Pane objects (methods). Calling methods here throws and aborts
    -- the handler, dropping WezTerm back to its default tab text.
    local pane = tab.active_pane
    local explicit = tab.tab_title -- set via tab:set_title(), else ""
    local osc = pane and pane.title -- the pane's OSC-2 title
    local proc = pane and pane.foreground_process_name
    if proc then
      proc = proc:match("([^/]+)$")
    end

    -- A user- (or program-) set, non-numeric tab title always wins.
    if explicit and explicit ~= "" and not explicit:match("^%d+$") then
      return explicit
    end

    -- cwd basename, collapsing $HOME to ~.
    local dir
    local cwd_uri = pane and pane.current_working_dir
    if cwd_uri then
      local cwd = cwd_uri.file_path or tostring(cwd_uri)
      local home = os.getenv("HOME") or ""
      if home ~= "" and cwd == home then
        dir = "~"
      else
        dir = cwd:match("([^/]+)/?$") or cwd
      end
    end

    -- Pick the label. Prefer the OSC-2 title when it carries real info, but
    -- WezTerm defaults pane.title to the bare process name ("zsh") when nothing
    -- sets an OSC title -- skip that and fall back to the cwd folder so a shell
    -- pane shows its directory rather than the word "zsh".
    local label
    if osc and osc ~= "" and not osc:match("^%d+$") and not SHELLS[osc:lower()] then
      label = osc
    end
    label = label or dir or proc or "shell"

    -- Prefix a sigil process icon when one is known (reset=true so the icon's
    -- color doesn't bleed into the label). Unknown procs (fallback=false)
    -- render the label alone.
    if proc and sigil_ok and ribbon_ok then
      local icon_items = sigil.items(proc, { padding = "right", fallback = false, reset = true })
      if icon_items and #icon_items > 0 then
        local r = ribbon.new("tab")
        r:append_items(icon_items)
        r:append(nil, nil, label)
        return r:items()
      end
    end
    return label
  end)

  -- Hyperlink rules: start with defaults, then add custom patterns
  local hyperlink_rules = wezterm.default_hyperlink_rules()

  -- Nix store paths as file:// links
  table.insert(hyperlink_rules, {
    regex = [[(/nix/store/[a-z0-9]{32}[a-zA-Z0-9._+%-][^\s]*)]],
    format = "file://$1",
  })

  -- owner/repo#NNN → GitHub issue URL
  table.insert(hyperlink_rules, {
    regex = [[([a-zA-Z0-9_.-]+/[a-zA-Z0-9_.-]+)#([0-9]+)]],
    format = "https://github.com/$1/issues/$2",
  })

  config.hyperlink_rules = hyperlink_rules

  -- Extended quick-select patterns
  config.quick_select_patterns = {
    "/nix/store/[a-z0-9]{32}[a-zA-Z0-9._+%-][^\\s]*",
    "[0-9a-f]{40}",
    "(?<![0-9a-f])[0-9a-f]{7}(?![0-9a-f])",
    "[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}",
    "/[^\\s]+",
  }

  -- workspace-manager: seshy session picker + layout persistence across restarts.
  -- We feed its switcher from `sy list`, bind it to SUPER+s (see below), and also
  -- surface it in the command palette. We do NOT use the plugin's own
  -- apply_to_config keybindings (they'd shadow vim's CTRL+[).
  local wm_ok, wm = plugin_loader.load("workspace-manager")
  if not wm_ok then
    wezterm.log_warn("Failed to load workspace-manager.wezterm: " .. tostring(wm))
  end
  if wm_ok then
    local home = os.getenv("HOME") or ""
    local seshy_dir = home .. "/.local/state/seshy/sessions"

    -- wezterm.run_child_process runs under the GUI process's own environment,
    -- whose PATH (when launched from Finder/Dock on macOS) omits ~/.local/bin
    -- where `sy` lives — so a bare "sy" silently fails and the switcher shows
    -- no sessions. Resolve an absolute path from the PATH the config knows
    -- about (env.json), falling back to the conventional install dir.
    local sy_bin = home .. "/.local/bin/sy"
    do
      local env = utils.load_json_file(utils.get_config_path("env.json"))
      for dir in (env and env.PATH or ""):gmatch("[^:]+") do
        local candidate = dir .. "/sy"
        local fh = io.open(candidate, "r")
        if fh then
          fh:close()
          sy_bin = candidate
          break
        end
      end
    end

    -- Replace the default choice provider: list seshy sessions instead of
    -- scanning a projects dir. `sy list` prints a header row then one row per
    -- session; column 1 is the session name.
    --
    -- The list always leads with a pinned "default" entry — the home-base
    -- workspace WezTerm starts in. Selecting it does SwitchToWorkspace{name=
    -- "default"} (create-if-absent), the one switcher path back from any seshy
    -- session. It's seeded first so it survives an empty/header-only `sy list`
    -- or a missing/erroring `sy` binary (the early return still carries it).
    wm.get_choices = function()
      -- Roll up live agent state once and decorate each session row with its
      -- state icon, reason, and age, sorted so the longest-blocked session is
      -- on top. Sourced from the same helper the statusline reads, so the two
      -- surfaces always agree on which session is worst.
      local sessions, panes = agent_session_states()
      local now = os.time()

      -- Aggregate the per-pane view into per-session (== per-workspace) detail:
      -- repo (in-memory cwd basename; branch/dirty aren't derivable here and the
      -- state-file bus carries them for out-of-WezTerm consumers), total agent
      -- pane count, blocked (rank >= working) count, and the worst pane's agent.
      -- Keyed by workspace, which seshy makes equal to the session name.
      local agg = {}
      for _, rec in ipairs(panes) do
        local a = agg[rec.workspace]
        if not a then
          a = { count = 0, blocked = 0, repo = "", agent = "", worst_rank = 0, worst_status = nil }
          agg[rec.workspace] = a
        end
        a.count = a.count + 1
        if a.repo == "" and rec.repo ~= "" then
          a.repo = rec.repo
        end
        if rec.rank >= agent_state_rank.working then
          a.blocked = a.blocked + 1
        end
        if rec.rank > a.worst_rank then
          a.worst_rank = rec.rank
          a.worst_status = rec.status
          if rec.agent ~= "" then
            a.agent = rec.agent
          end
        end
      end

      local default_choice = { name = "default", path = home, label = "default" }
      local rows = {}

      local ok, stdout = pcall(function()
        local success, out = wezterm.run_child_process({ sy_bin, "list" })
        if not success then
          error("sy list failed")
        end
        return out
      end)
      if ok and stdout then
        local first = true
        for _, line in ipairs(wezterm.split_by_newlines(stdout)) do
          if first then
            first = false
          elseif line ~= "" then
            local name = line:match("^(%S+)")
            if name then
              local st = sessions[name]
              local label = name
              if st then
                local icon = agent_state_icons[st.status] or "●"
                label = icon .. " " .. name
                -- repo · pane-count[ · blocked◔] · agent, between name and reason.
                -- Fields absent in the in-memory rollup (branch, dirty) are simply
                -- omitted — the row degrades to whatever is known.
                local a = agg[name]
                if a then
                  local meta = {}
                  if a.repo ~= "" then
                    meta[#meta + 1] = a.repo
                  end
                  if a.count > 0 then
                    local counts = tostring(a.count)
                    if a.blocked > 0 then
                      counts = counts .. " · " .. a.blocked .. (agent_state_icons[a.worst_status] or "")
                    end
                    meta[#meta + 1] = counts
                  end
                  if a.agent ~= "" then
                    meta[#meta + 1] = a.agent
                  end
                  if #meta > 0 then
                    label = label .. "  " .. table.concat(meta, " · ")
                  end
                end
                local age = st.since and format_age(now - st.since) or ""
                if st.reason ~= "" then
                  label = label .. " — " .. st.reason
                end
                if age ~= "" then
                  label = label .. " (" .. age .. ")"
                end
              end
              table.insert(rows, {
                name = name,
                path = seshy_dir .. "/" .. name,
                label = label,
                -- sort keys (stripped from the choice the plugin sees)
                _rank = st and st.rank or 0,
                _since = st and st.since or nil,
              })
            end
          end
        end
      end

      -- Urgency sort: higher rank first, then older `since` (longer wait), then
      -- name for stability. Stateless sessions (rank 0) fall to the bottom.
      table.sort(rows, function(a, b)
        if a._rank ~= b._rank then
          return a._rank > b._rank
        end
        if a._rank > 0 and a._since ~= b._since then
          return (a._since or now) < (b._since or now)
        end
        return a.name < b.name
      end)

      local choices = { default_choice }
      for _, row in ipairs(rows) do
        table.insert(choices, { name = row.name, path = row.path, label = row.label })
      end
      return choices
    end

    wm.session_enabled = true
    -- Always launch (and relaunch after quit) into the "default" workspace
    -- rather than auto-restoring the most-recently-used session. With this
    -- false the plugin registers no gui-startup restore handler, so WezTerm's
    -- own startup honors config.default_workspace ("default") below. Sessions
    -- still save (session_enabled) and still restore when switched into via the
    -- switcher; only the startup auto-restore is suppressed.
    wm.session_restore_on_startup = false
    wm.session_state_dir = home .. "/.local/state/wezterm/workspace_state"
    wm.workspace_switcher_sort = "recency"

    -- apply_to_config appends its own leader bindings and an in-switcher
    -- key_table (config.key_tables.workspace_switcher_actions). We keep the
    -- key_table — it drives the switcher's own UI — but strip the four
    -- user-facing leader bindings it injects: we open the switcher from SUPER+s
    -- below, and CTRL+[ (= ESC) in particular would shadow vim. Remove by
    -- (key, mods) identity so the override is explicit and immune to any
    -- change in the plugin's append order. None of these combos are bound by
    -- our own keybindings.lua, so this only removes the plugin's.
    wm.apply_to_config(config)
    local wm_injected_keys = {
      { key = "s", mods = "LEADER" },
      { key = "S", mods = "LEADER" },
      { key = "]", mods = "CTRL" },
      { key = "[", mods = "CTRL" },
    }
    if config.keys then
      for _, injected in ipairs(wm_injected_keys) do
        for i = #config.keys, 1, -1 do
          local k = config.keys[i]
          if k.key == injected.key and k.mods == injected.mods then
            table.remove(config.keys, i)
          end
        end
      end
    end

    -- SUPER+s opens the switcher. Bound here (not keybindings.lua) because it
    -- needs this configured wm instance; mirrors the locked-mode passthrough the
    -- other smart keybinds use. ssh moved to SUPER+SHIFT+s.
    config.keys = config.keys or {}
    table.insert(config.keys, {
      key = "s",
      mods = "SUPER",
      action = wezterm.action_callback(function(win, pane)
        if keybindings.locked_mode then
          win:perform_action({ SendKey = { key = "s", mods = "SUPER" } }, pane)
          return
        end
        win:perform_action(wm.workspace_switcher(), pane)
      end),
    })

    -- Also expose the switcher through the command palette (reachable via the
    -- existing SUPER+: / SUPER+; / CTRL+; palette bindings).
    wezterm.on("augment-command-palette", function(_window, _pane)
      return {
        {
          brief = "Switch seshy session / workspace",
          action = wm.workspace_switcher(),
        },
        {
          brief = "Switch to previous workspace",
          action = wm.switch_to_previous_workspace(),
        },
      }
    end)
  end

  -- Agent jump + picker. Bound here (not keybindings.lua) because they need the
  -- rollup helpers in scope, mirroring the SUPER+s switcher above; both honor the
  -- locked-mode passthrough. `CTRL+g` (locked-mode toggle) is unaffected.
  config.keys = config.keys or {}

  -- SUPER+g: jump straight to the single worst blocked pane across all
  -- workspaces (throwaway sibling tabs included). No-op when nothing is blocked.
  table.insert(config.keys, {
    key = "g",
    mods = "SUPER",
    action = wezterm.action_callback(function(win, pane)
      if keybindings.locked_mode then
        win:perform_action({ SendKey = { key = "g", mods = "SUPER" } }, pane)
        return
      end
      activate_agent_pane(win, pane, worst_agent_pane())
    end),
  })

  -- SUPER+SHIFT+g: pick from every blocked pane (session · repo · agent · reason
  -- · age), urgency-ordered. Selecting one jumps to it; a since-closed pane
  -- no-ops on activation.
  table.insert(config.keys, {
    key = "g",
    mods = "SUPER|SHIFT",
    action = wezterm.action_callback(function(win, pane)
      if keybindings.locked_mode then
        win:perform_action({ SendKey = { key = "g", mods = "SUPER|SHIFT" } }, pane)
        return
      end
      local _, panes = agent_session_states()
      local now = os.time()
      local list = {}
      for _, rec in ipairs(panes) do
        if rec.rank >= agent_state_rank.working then
          list[#list + 1] = rec
        end
      end
      if #list == 0 then
        return
      end
      table.sort(list, function(a, b)
        if a.rank ~= b.rank then
          return a.rank > b.rank
        end
        return (a.since or now) < (b.since or now)
      end)

      local by_id = {}
      local choices = {}
      for _, rec in ipairs(list) do
        by_id[tostring(rec.pane_id)] = rec
        local icon = agent_state_icons[rec.status] or "●"
        local parts = {}
        if rec.workspace ~= "" then
          parts[#parts + 1] = rec.workspace
        end
        if rec.repo ~= "" then
          parts[#parts + 1] = rec.repo
        end
        if rec.agent ~= "" then
          parts[#parts + 1] = rec.agent
        end
        local label = icon .. " " .. table.concat(parts, " · ")
        if rec.reason ~= "" then
          label = label .. " — " .. rec.reason
        end
        local age = rec.since and format_age(now - rec.since) or ""
        if age ~= "" then
          label = label .. " (" .. age .. ")"
        end
        choices[#choices + 1] = { id = tostring(rec.pane_id), label = label }
      end

      win:perform_action(
        wezterm.action.InputSelector({
          title = "Jump to blocked agent",
          choices = choices,
          action = wezterm.action_callback(function(inner_win, inner_pane, id, _label)
            if not id then
              return
            end
            activate_agent_pane(inner_win, inner_pane, by_id[id])
          end),
        }),
        pane
      )
    end),
  })
end

return M
